"""An exact, vocabulary-free UTF-8 byte tokenizer for the scratch model."""

from numbers import Integral


VERSION = "b3-utf8-bytes-v1"


class ByteTokenizer:
    """Each UTF-8 byte is its own token; no corpus or downloaded assets are used."""

    vocab_size = 256
    version = VERSION

    def encode(self, text: str) -> list[int]:
        if not isinstance(text, str):
            raise TypeError("Tokenizer input must be text.")
        return list(text.encode("utf-8", errors="strict"))

    def decode(self, ids) -> str:
        validated = []
        try:
            iterator = iter(ids)
        except TypeError as exc:
            raise TypeError("Token ids must be an iterable of integers.") from exc
        for token in iterator:
            if isinstance(token, bool) or not isinstance(token, Integral):
                raise ValueError("Every token id must be an integer in [0, 255].")
            if not 0 <= int(token) < self.vocab_size:
                raise ValueError("Every token id must be an integer in [0, 255].")
            validated.append(int(token))
        # A generated byte sequence can end halfway through a Unicode character.
        return bytes(validated).decode("utf-8", errors="replace")
