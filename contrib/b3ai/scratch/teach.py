import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import time

import numpy as np

from .checkpoint import load_checkpoint, save_checkpoint
from .data import BASELINE, corpus_bytes, load_curriculum, split_hash, validate_records
from .model import AdamW, ModelConfig, Transformer
from .tokenizer import ByteTokenizer
from .train import atomic_write, implementation_hash

_DIALOGUE = re.compile(r"\nUser: ([^\n\r\x00]+)\nAssistant: ([^\n\r\x00]+)\n\Z")


def parse_dialogue(record):
    text = record.get("text") if isinstance(record, dict) else None
    if not isinstance(text, str):
        raise ValueError("A teaching record needs a single plain-text conversation.")
    match = _DIALOGUE.fullmatch(text)
    if match is None or not all(part.strip() for part in match.groups()):
        raise ValueError("Use one nonempty User/Assistant turn with a final newline.")
    try:
        text.encode("utf-8", errors="strict")
    except UnicodeEncodeError as error:
        raise ValueError("Teaching text must contain valid Unicode.") from error
    question, answer = match.groups()
    return f"\nUser: {question}\nAssistant: ", answer + "\n"


def _encoded(record, context_length):
    prompt, answer = parse_dialogue(record)
    tokenizer = ByteTokenizer()
    prefix, ending = tokenizer.encode(prompt), tokenizer.encode(answer)
    ids = prefix + ending
    if len(ids) - 1 > context_length:
        raise ValueError("A complete teaching turn exceeds the model context; no text was truncated.")
    return ids, len(prefix)


def _pack(records, context_length):
    encoded = [_encoded(row, context_length) for row in records]
    length = max(len(ids) - 1 for ids, _ in encoded)
    x = np.zeros((len(records), length), dtype=np.int64)
    y = np.zeros_like(x)
    mask = np.zeros(x.shape, dtype=np.float32)
    for index, (ids, prefix_length) in enumerate(encoded):
        count = len(ids) - 1
        x[index, :count], y[index, :count] = ids[:-1], ids[1:]
        # y[prefix_length - 1] predicts the first answer byte. Its final newline
        # is supervised too; prompt targets and padding carry zero loss.
        mask[index, prefix_length - 1:count] = 1
    return x, y, mask


def dialogue_batch(records, batch_size, context_length, rng):
    if not records or type(batch_size) is not int or not 1 <= batch_size <= 16:
        raise ValueError("Teaching batches need records and a size from 1 to 16.")
    if type(context_length) is not int or not 1 <= context_length <= 256:
        raise ValueError("Choose a teaching context from 1 to 256 bytes.")
    for row in records:
        _encoded(row, context_length)
    selected = [records[int(rng.integers(len(records)))] for _ in range(batch_size)]
    return _pack(selected, context_length)


def evaluate_dialogues(model, records):
    """Token-weighted answer loss over every complete record, without RNG use."""
    if not records:
        raise ValueError("Evaluation needs teaching records.")
    loss_sum, token_count = 0.0, 0
    for start in range(0, len(records), 4):
        x, y, mask = _pack(records[start:start + 4], model.config.context_length)
        logits = model.forward(x).astype(np.float64)
        logits -= logits.max(axis=-1, keepdims=True)
        losses = np.log(np.exp(logits).sum(axis=-1)) - np.take_along_axis(logits, y[..., None], axis=-1)[..., 0]
        loss_sum += float(np.sum(losses * mask))
        token_count += int(mask.sum())
    result = loss_sum / token_count
    if not math.isfinite(result):
        raise ValueError("Teaching evaluation produced a non-finite loss.")
    return result


def reply(model, prompt, max_new_tokens=96, temperature=0, seed=42):
    """Return generated bytes up to the learned newline; substitute no answer."""
    if not isinstance(prompt, str) or not prompt.strip() or "\0" in prompt:
        raise ValueError("Provide a nonempty, plain-text prompt.")
    if type(max_new_tokens) is not int or not 1 <= max_new_tokens <= 256:
        raise ValueError("Request 1 to 256 new bytes.")
    tokenizer = ByteTokenizer()
    try:
        ids = tokenizer.encode(prompt)
    except UnicodeEncodeError as error:
        raise ValueError("The prompt must contain valid Unicode.") from error
    if len(ids) + max_new_tokens > model.config.context_length:
        raise ValueError("The full prompt and requested answer exceed the context.")
    result = model.generate(ids, max_new_tokens, temperature=temperature, seed=seed)
    output = result[len(ids):]
    if 10 in output:
        return tokenizer.decode(output[:output.index(10)]), "stop"
    return tokenizer.decode(output), "length"


def teaching_hash():
    digest = hashlib.sha256(implementation_hash().encode())
    for name in ("teach.py", "dialogue_data.py"):
        digest.update(name.encode() + b"\0")
        digest.update(Path(__file__).with_name(name).read_bytes())
    return digest.hexdigest()


def fit(output, records, *, steps=1000, config=None, batch_size=4,
        learning_rate=0.001, evaluation_interval=100, patience=3, initialize_from=None):
    for name, value, upper in (("steps", steps, 5000), ("batch_size", batch_size, 16),
                               ("evaluation_interval", evaluation_interval, 5000), ("patience", patience, 20)):
        if type(value) is not int or not 1 <= value <= upper:
            raise ValueError(f"{name} must be an integer from 1 to {upper}.")
    if isinstance(learning_rate, bool) or not isinstance(learning_rate, (int, float)) or not math.isfinite(learning_rate) or not 0 < learning_rate <= 0.1:
        raise ValueError("Choose a finite positive learning rate up to 0.1.")
    validate_records(records)
    config = config or ModelConfig(context_length=256)
    if config.vocab_size != 256 or config.context_length > 256:
        raise ValueError("Teaching requires the byte vocabulary and a context up to 256.")
    for row in records:
        _encoded(row, config.context_length)
    output = Path(output)
    if output.exists():
        raise ValueError("Refusing to replace an existing teaching experiment directory.")
    train_records = [row for row in records if row["split"] == "train"]
    validation_records = [row for row in records if row["split"] == "validation"]
    encoded = corpus_bytes(records)
    model = Transformer(config)
    parent = None
    if initialize_from is not None:
        path = Path(initialize_from)
        prior, prior_optimizer, prior_metadata = load_checkpoint(path)
        if prior.dtype != np.dtype(np.float32):
            raise ValueError("Teaching transfer requires float32 parameters; no implicit dtype conversion is permitted.")
        if prior_metadata.get("readiness") != "experimental":
            raise ValueError("Transfer requires an explicitly experimental checkpoint.")
        previous = prior.config.to_dict()
        requested = config.to_dict()
        if any(previous[key] != requested[key] for key in requested if key != "context_length"):
            raise ValueError("Only the context size can change when continuing this model.")
        for name, value in prior.params.items():
            if name == "position_embedding":
                count = min(value.shape[0], model.params[name].shape[0])
                model.params[name][:count] = value[:count]
            else:
                model.params[name][...] = value
        parent = {"checkpoint_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                  "prior_optimizer_steps": prior_optimizer.steps, "prior_stage": prior_metadata.get("stage"),
                  "prior_context_length": prior.config.context_length,
                  "new_positions": max(0, config.context_length - prior.config.context_length)}
    # Reset moments for the changed loss/curriculum. This is a new teaching stage,
    # not an exact resume of the preceding byte-prediction experiment.
    optimizer = AdamW(model.params)
    rng = np.random.default_rng(config.seed + 1)
    # Exclusive creation reserves this run before expensive work. A competing
    # fit cannot take the same output, even if both passed the earlier check.
    output.mkdir(parents=True, exist_ok=False)
    started = time.monotonic()
    initial = {"train_loss": evaluate_dialogues(model, train_records),
               "validation_loss": evaluate_dialogues(model, validation_records)}
    best_loss, best_step = initial["validation_loss"], 0
    best_parameters = {name: value.copy() for name, value in model.params.items()}
    best_optimizer, best_rng = optimizer.state_dict(), rng.bit_generator.state
    history, stale, attempted = [], 0, 0
    print(json.dumps({"event": "start", "stage": "sanity-dialogue", "parent": parent, **initial}), flush=True)
    for index in range(1, steps + 1):
        x, y, mask = dialogue_batch(train_records, batch_size, config.context_length, rng)
        _, grads = model.loss_and_grad(x, y, mask)
        optimizer.step(model.params, grads, lr=learning_rate, clip_norm=1.0)
        attempted = index
        if index % evaluation_interval == 0 or index == steps:
            metrics = {"step": optimizer.steps, "train_loss": evaluate_dialogues(model, train_records),
                       "validation_loss": evaluate_dialogues(model, validation_records)}
            history.append(metrics)
            print(json.dumps({"event": "evaluation", **metrics}), flush=True)
            if metrics["validation_loss"] < best_loss:
                best_loss, best_step, stale = metrics["validation_loss"], index, 0
                best_parameters = {name: value.copy() for name, value in model.params.items()}
                best_optimizer, best_rng = optimizer.state_dict(), rng.bit_generator.state
            else:
                stale += 1
            if stale >= patience:
                break
    for name in model.params:
        model.params[name][...] = best_parameters[name]
    optimizer.load_state_dict(best_optimizer)
    from .dialogue_data import builtin_dialogues
    builtin = encoded == corpus_bytes(builtin_dialogues())
    report = {"stage": "sanity-dialogue", "readiness": "experimental", "initialization": "random",
              "pretrained_weights": False, "parent": parent, "optimizer_reset": parent is not None,
              "config": config.to_dict(), "parameters": model.parameter_count,
              "completed_steps": attempted, "best_step": best_step, "saved_optimizer_steps": optimizer.steps,
              "requested_steps": steps, "stopped_early": attempted < steps, "patience": patience,
              "batch_size": batch_size, "learning_rate": learning_rate, "evaluation_interval": evaluation_interval,
              "elapsed_seconds": time.monotonic() - started, "initial_metrics": initial,
              "best_validation_loss": best_loss, "final_metrics": {
                  "train_loss": evaluate_dialogues(model, train_records),
                  "validation_loss": evaluate_dialogues(model, validation_records)},
              "evaluations_this_run": history, "dataset_sha256": hashlib.sha256(encoded).hexdigest(),
              "training_split_hash": split_hash(records, "train"), "validation_split_hash": split_hash(records, "validation"),
              "teaching_implementation_sha256": teaching_hash(), "training_baseline": BASELINE,
              "teacher_review": "source-reviewed teaching fixture" if builtin else "caller-declared review; not independently verified",
              "corpus_origin": "builtin-b3-dialogues" if builtin else "custom-dialogues",
              "train_records": len(train_records), "validation_records": len(validation_records),
              "objective": "Next-byte prediction on answer bytes and final newline only",
              "turn_ending": "Single newline byte, learned from answer targets",
              "limits": "Validation selects a checkpoint. This is not an independent B3 task accuracy test. No tools or node observations."}
    save_checkpoint(output / "model.npz", model, optimizer, {**report, "rng_state": best_rng})
    report["checkpoint_sha256"] = hashlib.sha256((output / "model.npz").read_bytes()).hexdigest()
    atomic_write(output / "corpus.jsonl", encoded)
    atomic_write(output / "report.json", (json.dumps(report, indent=2, sort_keys=True) + "\n").encode())
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("build-ai/scratch-dialogue"))
    parser.add_argument("--corpus", type=Path)
    parser.add_argument("--initialize-from", type=Path)
    parser.add_argument("--steps", type=int, default=1000)
    parser.add_argument("--evaluation-interval", type=int, default=100)
    parser.add_argument("--patience", type=int, default=3)
    parser.add_argument("--learning-rate", type=float, default=0.001)
    parser.add_argument("--context-length", type=int, default=256)
    parser.add_argument("--prompt", help="After training, generate an actual short answer to this question")
    args = parser.parse_args()
    from .dialogue_data import builtin_dialogues
    try:
        records = load_curriculum(args.corpus) if args.corpus else builtin_dialogues()
        report = fit(args.output, records, steps=args.steps, config=ModelConfig(context_length=args.context_length),
                     learning_rate=args.learning_rate, evaluation_interval=args.evaluation_interval,
                     patience=args.patience, initialize_from=args.initialize_from)
        print(json.dumps({"event": "saved", "checkpoint": str(args.output / "model.npz"),
                          "best_step": report["best_step"], "readiness": "experimental"}), flush=True)
        if args.prompt:
            model, _, _ = load_checkpoint(args.output / "model.npz")
            answer, reason = reply(model, f"\nUser: {args.prompt}\nAssistant: ")
            print(json.dumps({"actual_output": answer, "finish_reason": reason}, ensure_ascii=False))
    except (OSError, ValueError, TypeError, KeyError, FloatingPointError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
